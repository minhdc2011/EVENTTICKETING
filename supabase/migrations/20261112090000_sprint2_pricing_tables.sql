-- NOTE for T6 notes: the RESTRICT foreign keys below are intentional (audit trail).
-- They block DELETE on KHU_VUC rows that have price-log entries (the organizer save RPCs in
-- 20261028100000_* delete/recreate zones) and block deleting an auth user (via
-- HO_SO_NGUOI_DUNG) who has price-log entries. Those RPCs are deliberately not changed here.
CREATE TABLE IF NOT EXISTS public."NHAT_KY_GIA" (
    "NhatKyGiaID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "KhuVucID" INT NOT NULL REFERENCES public."KHU_VUC"("KhuVucID") ON DELETE RESTRICT,
    -- UNIQUE nullable: at most one log entry per proposal; manual entries may have NULL.
    "DeXuatID" BIGINT UNIQUE REFERENCES public."DE_XUAT_GIA"("DeXuatID") ON DELETE RESTRICT,
    "LoaiBienDong" VARCHAR(30) NOT NULL,
    "GiaCu" NUMERIC(12,2) NOT NULL,
    "GiaMoi" NUMERIC(12,2) NOT NULL,
    "TyLeThayDoiPhanTram" NUMERIC(6,2) NOT NULL,
    "LyDoThayDoi" TEXT NOT NULL,
    -- Changed vs. draft (implicit NO ACTION): explicit ON DELETE RESTRICT so the audit link
    -- to the acting user can never be silently lost.
    "NguoiThucHienID" UUID REFERENCES public."HO_SO_NGUOI_DUNG"("NguoiDungID") ON DELETE RESTRICT,
    "ThoiGianApDung" TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_loai_bien_dong" CHECK ("LoaiBienDong" IN ('KHOI_TAO', 'DUYET_DE_XUAT_AI', 'DIEU_CHINH_THU_CONG'))
