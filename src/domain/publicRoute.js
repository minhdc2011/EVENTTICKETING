export function deduplicateSlug(slug) {
  if (!slug || typeof slug !== 'string') return '';
  let trimmed = slug.trim().toLowerCase();
  while (trimmed.length >= 4 && trimmed.length % 2 === 0) {
    const half = trimmed.slice(0, trimmed.length / 2);
    if (half === trimmed.slice(trimmed.length / 2) && /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(half)) {
      trimmed = half;
    } else {
      break;
    }
  }
  return trimmed;
}

const ORGANIZER_PAGES = ['dashboard', 'login'];
const ACCOUNT_SUBPAGES = ['overview', 'login', 'register'];
const ROUTE_KEYWORDS = ['organizer', 'account', 'login', 'register', 'events'];

/**
 * Resolves the public route from the query (`?route=/...`), the hash (`#/...`) or the path.
 * Unknown routes resolve to {kind: 'notfound'} instead of silently showing the catalog:
 *  - an explicit route (query/hash) that matches nothing, e.g. `?route=/abc`
 *  - `account/<unknown>` and `organizer/<unknown>`, extra segments after a known pattern
 *  - a path under `basePath` that matches nothing (only when `basePath` is given, because without it the
 *    deployment prefix cannot be told apart from a page name).
 * @param {string} pathname
 * @param {string} fallbackEventSlug
 * @param {string} [hash]
 * @param {string} [search]
 * @param {string} [basePath] deployment base such as '/' or '/EVENTTICKETING/'
 */
export function resolvePublicRoute(pathname, fallbackEventSlug, hash = '', search = '', basePath) {
  const queryRoute = new URLSearchParams(search).get('route');
  const explicit = queryRoute?.startsWith('/') ? queryRoute : hash.startsWith('#/') ? hash.slice(1) : null;
  const rawRouteSource = explicit ?? pathname;
  // Be tolerant of links generated by older builds where `?preview=1` was
  // accidentally embedded in the route parameter itself.
  const routeSource = rawRouteSource.split(/[?#]/, 1)[0];
  // `index.html` is the document itself, not a page name (static hosts serve it at the base path)
  let segments = routeSource.split('/').filter((seg) => seg && seg !== 'index.html').map(decodeURIComponent);
  const notFound = {kind: 'notfound'};

  if (explicit === null && typeof basePath === 'string') {
    const baseSegments = basePath.split('/').filter(Boolean);
    if (baseSegments.every((seg, i) => segments[i] === seg)) segments = segments.slice(baseSegments.length);
  }

  const organizerIndex = segments.indexOf('organizer');
  if (organizerIndex >= 0) {
    const organizerPage = segments[organizerIndex + 1] || 'dashboard';
    if (!ORGANIZER_PAGES.includes(organizerPage) || segments.length > organizerIndex + 2) return notFound;
    return {kind: 'organizer', page: organizerPage};
  }
  const accountIndex = segments.findIndex((seg) => seg === 'account' || seg === 'login' || seg === 'register');
  if (accountIndex >= 0) {
    const seg = segments[accountIndex];
    const sub = seg === 'account' ? segments[accountIndex + 1] : undefined;
    if (seg === 'account' && sub !== undefined && !ACCOUNT_SUBPAGES.includes(sub)) return notFound;
    if (segments.length > accountIndex + (seg === 'account' && sub !== undefined ? 2 : 1)) return notFound;
    const page = seg === 'register' ? 'register' : seg === 'login' ? 'login' : (sub || 'overview');
    return {kind: 'account', page};
  }
  const eventIndex = segments.indexOf('events');
  if (eventIndex < 0) {
    const hasUnknownPage = segments.length > 0 && (explicit !== null || typeof basePath === 'string');
    return hasUnknownPage ? notFound : {kind: 'catalog'};
  }
  const rawEventSlug = segments[eventIndex + 1];
  if (!rawEventSlug) return {kind: 'catalog'};
  const eventSlug = deduplicateSlug(rawEventSlug);
  const after = segments[eventIndex + 2];
  if (after !== undefined) {
    const showSlug = segments[eventIndex + 3];
    if (after !== 'shows' || !showSlug || segments.length > eventIndex + 4) return notFound;
    return {kind: 'detail', eventSlug, showSlug};
  }
  return {kind: 'detail', eventSlug};
}

export function buildPublicPath(pathname, target) {
  const segments = pathname.split('/').filter(Boolean);
  const eventIndex = segments.indexOf('events');
  const baseSegments = eventIndex >= 0
    ? segments.slice(0, eventIndex)
    : pathname.endsWith('/') ? segments : segments.slice(0, -1);
  const base = `/${baseSegments.join('/')}${baseSegments.length ? '/' : ''}`;
  const [pathOnly, queryOrHash] = target.replace(/^\/+/, '').split(/([?#].*)/, 2);
  const cleanTarget = pathOnly.split('/').map((seg, idx, arr) => {
    if (
      arr[idx - 1] === 'events' ||
      (idx === 0 && seg !== 'events' && seg !== 'organizer' && seg !== 'account' && seg !== 'login' && seg !== 'register')
    ) {
      return deduplicateSlug(seg);
    }
    return seg;
  }).join('/');
  const suffix = queryOrHash?.startsWith('?')
    ? `&${queryOrHash.slice(1)}`
    : queryOrHash || '';
  return `${base}?route=/${cleanTarget}${suffix}`;
}

export function navigatePublicRoute(target) {
  if (typeof window === 'undefined') return;
  const nextUrl = buildPublicPath(window.location.pathname, target);
  window.history.pushState({}, '', nextUrl);
  window.dispatchEvent(new PopStateEvent('popstate'));
}
